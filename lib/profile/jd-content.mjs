// Browser-safe source boundaries shared by intake, comparison and review UI.
// No fetching, document parsers or Profile domain imports belong in this module.
export const PRIMARY_JD_HEADING=/^(?:full (?:job )?description|job description|about (?:the |this )?role|responsibilities|what you(?:'ll| will) do|the role|position description)\s*:?\s*$/i;
export const AI_JD_HEADING=/^(?:ai(?:[- ]generated)?(?:\s+job)?\s+(?:summary|overview)|built in ai summary|(?:job )?summary generated by ai|top skills)(?:\s*[:\u2014-].*)?$/i;
export const RECOMMENDATION_JD_HEADING=/^(?:(?:similar|related|recommended) (?:jobs|roles)|you (?:might|may) also (?:like|be interested)|more jobs (?:at|like this)|other (?:open )?(?:jobs|roles)|explore (?:similar|more) (?:jobs|roles))(?:\b.*)?$/i;

/** Filter stored JD paragraphs, preserving original IDs and contiguous exact spans. */
export function primaryJDSegments(segments){
  let skippingAI=false,ended=false,seenPrimary=false;
  const output=[];
  for(const segment of Array.isArray(segments)?segments:[]){
    if(!segment||typeof segment.text!=='string'||ended)continue;
    const ranges=[];let offset=0,current=null;
    for(const raw of segment.text.match(/[^\n]*(?:\n|$)/g)||[]){
      if(!raw)continue;
      const line=raw.trim();let start=offset,end=offset+raw.length,keep=true;
      if(AI_JD_HEADING.test(line)){skippingAI=true;keep=false;}
      if(PRIMARY_JD_HEADING.test(line)){skippingAI=false;seenPrimary=true;keep=true;}
      else if(skippingAI){
        const primary=raw.match(/\b(?:full (?:job )?description|job description|about the role)\s*:?/i);
        if(primary){start+=primary.index;skippingAI=false;seenPrimary=true;keep=true;}else keep=false;
      }
      if(RECOMMENDATION_JD_HEADING.test(line)){if(seenPrimary)ended=true;else skippingAI=true;keep=false;}
      if(/^(?:sign in|log in|sign up|save job|save|share|apply now|menu|search jobs|browse jobs|job alerts|privacy policy|cookie preferences)$/i.test(line))keep=false;
      if(ended)keep=false;
      if(keep&&line.length>60&&/\b(?:responsibilities|requirements|qualifications|job description|experience)\b/i.test(line))seenPrimary=true;
      if(keep){if(current&&current.end===offset)current.end=end;else{current={start,end};ranges.push(current);}}
      else current=null;
      offset=end;
    }
    // Never join passages into a quotation that did not exist in the source.
    const longest=ranges.sort((a,b)=>(b.end-b.start)-(a.end-a.start))[0];
    if(longest){const content=segment.text.slice(longest.start,longest.end).trim();if(content)output.push({...segment,text:content});}
  }
  return output;
}
